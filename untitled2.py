import random

print("================================")
print("       CARROT IN A BOX")
print("================================")

# 1. Title and Input
input("Press Enter to start the game...")

player1 = input("Enter Player 1's name: ")
player2 = input("Enter Player 2's name: ")

# 2. Player Names and Boxes
firstBox = "RED BOX"
secondBox = "GOLD BOX"

print("\n" + player1 + " gets the " + firstBox)
print(player2 + " gets the " + secondBox)

# 3. Random Carrot Placement
carrotInFirstBox = random.randint(1, 2) == 1

# 4. Displaying the Carrot
print("\n" + player1 + ", look inside your box!")
input("Press Enter when ready...")

if carrotInFirstBox:
    print("\nYour RED BOX contains the CARROT!")
else:
    print("\nYour RED BOX is EMPTY!")

input("\n" + player2 + ", close your eyes and press Enter.")

print("\n" * 30)

# 5. Bluffing and Box Swapping
print(player1 + ", tell " + player2 + " whether you have the carrot.")
print("You can tell the truth or bluff!")

input("\n" + player2 + ", open your eyes.")
print(player2 + ", do you want to swap boxes?")

while True:
    choice = input("Enter YES or NO: ").strip().upper()

    if choice == "YES" or choice == "NO":
        break
    else:
        print("Invalid choice! Please enter YES or NO.")

if choice == "YES":
    carrotInFirstBox = not carrotInFirstBox
    firstBox, secondBox = secondBox, firstBox

# 6. Displaying the Winner
print("\n================================")
print("          FINAL RESULT")
print("================================")

if carrotInFirstBox:
    print("The carrot is in", firstBox)
    print("Congratulations,", player1, "! You win!")
else:
    print("The carrot is in", secondBox)
    print("Congratulations,", player2, "! You win!")

print("\nThank you for playing CARROT IN A BOX!")